import { chromium } from "playwright";
import fs from "node:fs/promises";
const output = new URL("../../../docs/screenshots/", import.meta.url);
await fs.mkdir(output, {recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1050}});
await page.goto("http://localhost:3000/register");
await page.getByLabel("Your name").fill("Demo Analyst");
await page.getByLabel("Organization").fill("DEMO · Research Studio");
await page.getByLabel("Email address").fill(`preview-${Date.now()}@example.com`);
await page.getByLabel("Password",{exact:true}).fill("local-preview-password");
await page.getByRole("button",{name:"Create workspace"}).click();
await page.waitForURL("**/dashboard");
await page.getByRole("heading",{name:"A clearer view of what matters."}).waitFor();
await page.screenshot({path:new URL("dashboard-desktop.png",output).pathname.replace(/^\/(\w:)/,"$1"),fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.waitForFunction(()=>document.querySelector(".sidebar").getBoundingClientRect().right <= 0);
await page.screenshot({path:new URL("dashboard-mobile.png",output).pathname.replace(/^\/(\w:)/,"$1"),fullPage:true});
await page.setViewportSize({width:1440,height:1050});
await page.waitForFunction(()=>document.querySelector(".sidebar").getBoundingClientRect().left === 0);
await page.goto("http://localhost:3000/research/new");
await page.getByLabel("Research question",{exact:true}).fill("Analyze the Indian EV market, compare major companies, and assess growth drivers and risks.");
await page.screenshot({path:new URL("research-new.png",output).pathname.replace(/^\/(\w:)/,"$1"),fullPage:true});
await browser.close();
console.log("Saved desktop, mobile and research input screenshots to docs/screenshots.");
